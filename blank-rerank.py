def rerank_rule(query, docs):
    """用**零成本规则**把候选块重新排序（不上模型的 rerank）。

    提示：先算一个"匹配分"，再按分降序。
      ① 命中数：query 的 bigram 里，有多少个在这个块里出现过
      ② 覆盖率：命中数 / query 的 bigram 总数（防止"长块天然占便宜"）
      ③ 连续命中加分：query 的 bigram 在原句里**连续**出现（说明是短语、不是散词）

    参数：query 是问题字符串；docs 是候选块文本列表（**已按向量分排好序**）
    返回：重排后的 docs 列表（长度不变）
    ⚠️ 验收要求：修好 A 的题 1 / 12 / 14（它们现在排不到第一）

    自检判据（写完自己打勾，别先看源码）：
      [ ] query 侧**只算一次** bigram 集合，不要每个块都重新切 query
      [ ] 遍历 docs 时**必须拿到下标**（顺序是「并列时的兜底」判据，见下）
      [ ] 排序键是**元组**，且靠前的元素优先 —— 主判据在前、兜底判据在后
      [ ] **兜底判据 = 原向量名次（越靠前越好）** → 注意符号：
          若存的是下标 `idx`（越小越好），排序时要用 **-idx**；若存的是名次 `rank`（从 1 起），直接用即可
      [ ] 排序方向 `reverse=True`；返回的是**块文本列表**，不是分数、不是下标
      [ ] 长度必须与入参 docs 相同（重排 ≠ 筛选）
    """
    # ------------------------------------------------------------------
    # TODO: 你来写（约 10 行）
    # 提示：
    #   第 1 步 —— 先把 query 切成 bigram 集合（只切一次）
    #   第 2 步 —— 准备一个空的结果容器
    #   第 3 步 —— 遍历 docs，**同时拿到下标**：每个块算「命中数」，把 (分, 兜底判据, 块) 塞进容器
    #             ⚠️ 想清楚：如果两个块「分」相同，谁该排前面？（答案 = 原本向量里更靠前的那个）
    #   第 4 步 —— 按元组降序排，取出第三列（块文本），返回列表
    # ------------------------------------------------------------------
    q_set = set(tokenize_zh(query))
    scored =[]
    for rank,doc in enumerate(docs):
        hit = len(q_set & set(tokenize_zh(doc)))
        scored.append((hit,-rank,doc))
    scored.sort(key=lambda t:(t[0],t[1]),reverse=True)
    return [t[2] for t in scored]



# ── 依赖：tokenize_zh（已给你，不是默写内容）─────────────────────────
def tokenize_zh(text, n=2):
    """字符 bigram 切分：把文本切成相邻两字一组（中文关键短语靠它原样命中）。"""
    t = text.replace("\n", " ").strip()
    if len(t) <= n:
        return [t] if t else []
    return [t[i:i + n] for i in range(len(t) - n + 1)]


